// 금액의 단위는 «원»이다(AGENTS.md: 「금액 단위는 내부에서 하나로 통일한다」).
// 원·만원·억원 변환이 표시 계층의 몫인 것처럼, 「원 미만은 금액이 아니다」를 계산 안에서
// 실제로 지키는 것은 이 파일 하나의 몫이다.

/**
 * 금액을 원 단위로 맞춘다.
 *
 * **원장 항목에는 쓰지 않는다.** 인출액·세금·잔액은 계좌가 «실제로 옮긴» 금액이라 그중
 * 하나만 반올림하면 기말 = 기초 + 투자총수익 + 외부유입 − 생활비 − 세금 − 건보료가 딱
 * 그만큼 어긋난다. 인출액이라면 방향도 나쁘다 — 내림은 매달 조금씩 «덜 주는» 계획이 되고,
 * 올림은 계좌에 없던 현금을 만든다. 반올림은 원장에서 «파생된» 잔여값(미달액)에만 쓴다.
 * 그 값은 다시 어떤 금액도 만들지 않고 0과 비교되거나 화면에 찍힐 뿐이다.
 *
 * 내림(truncate)이 아니라 반올림(round-half-up)인 이유: 내림은 매달 최대 1원씩 실제 미달을
 * «숨기는» 쪽으로만 치우친다. 반올림은 0.5원 미만의 잔돈만 사라지고 치우침이 없다.
 *
 * 원이 기준인 근거는 원장의 허용 오차(YearLedger의 ABSOLUTE_TOLERANCE_KRW)와 같다 —
 * 원 미만의 차이는 화면에 보이지 않으므로 사용자에게 설명할 수 있는 사실이 아니다.
 */
export function roundToWon(amount: number): number {
  return Math.round(amount);
}
